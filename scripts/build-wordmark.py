"""Rebuild the outlined brand asset; not part of the application build.

Usage: python scripts/build-wordmark.py <directory containing the source fonts>
Source files and license: Google Fonts / ofl/alegreya (SIL OFL 1.1).
Requires fontTools. The app ships outlines, not a font or remote font request.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]).resolve()
FONT_SOURCES = {
    "italic": ("Alegreya-Italic.ttf", "https://raw.githubusercontent.com/google/fonts/main/ofl/alegreya/Alegreya-Italic%5Bwght%5D.ttf"),
    "roman": ("Alegreya-Roman.ttf", "https://raw.githubusercontent.com/google/fonts/main/ofl/alegreya/Alegreya%5Bwght%5D.ttf"),
}


def face(name: str, weight: int):
    font = instantiateVariableFont(TTFont(SOURCE / FONT_SOURCES[name][0]), {"wght": weight})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap = BoundsPen(glyphs)
    glyphs[cmap[ord("H")]].draw(cap)
    return font, glyphs, cmap, cap.bounds[3]


def word(text, font, glyphs, cmap, scale, pairs):
    cursor, parts, boxes = 0.0, [], []
    previous = ""
    for char in text:
        cursor += pairs.get(previous + char, 0)
        glyph_name = cmap[ord(char)]
        glyph = glyphs[glyph_name]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        glyph.draw(pen)
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        x0, y0, x1, y1 = bounds.bounds
        boxes.append(((cursor + x0) * scale, y0 * scale, (cursor + x1) * scale, y1 * scale))
        parts.append((cursor * scale, scale, pen.getCommands()))
        cursor += font["hmtx"][glyph_name][0]
        previous = char
    return parts, (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))


roman_font, roman_glyphs, roman_cmap, roman_cap = face("roman", 500)
italic_font, italic_glyphs, italic_cmap, italic_cap = face("italic", 550)
life, life_box = word("Life", italic_font, italic_glyphs, italic_cmap, roman_cap / italic_cap, {"Li": -10, "if": -5, "fe": -8})
atlas, atlas_box = word("Atlas", roman_font, roman_glyphs, roman_cmap, 1, {"At": -35, "tl": -8, "as": -5})
seam = 60
atlas_origin = life_box[2] + seam - atlas_box[0]
left, bottom = min(life_box[0], atlas_origin + atlas_box[0]), min(life_box[1], atlas_box[1])
right, top = max(life_box[2], atlas_origin + atlas_box[2]), max(life_box[3], atlas_box[3])
padding = 36
width, height = right - left + 2 * padding, top - bottom + 2 * padding


def number(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


groups = []
for origin, parts in [(0, life), (atlas_origin, atlas)]:
    for x, scale, outline in parts:
        groups.append(f'<path transform="translate({number(origin + x)} 0) scale({number(scale)})" d="{outline}"/>')
svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" class="brand-wordmark" '
    f'viewBox="0 0 {number(width)} {number(height)}" width="156" height="{number(156 * height / width)}" '
    f'fill="currentColor" aria-hidden="true" focusable="false">'
    f'<g transform="translate({number(padding - left)} {number(padding + top)}) scale(1 -1)">'
    + "".join(groups) + "</g></svg>"
)
brand_dir = ROOT / "public" / "brand"
brand_dir.mkdir(exist_ok=True)
(brand_dir / "lifeatlas-wordmark.svg").write_text(svg + "\n", encoding="utf-8")
(ROOT / "src" / "wordmark.ts").write_text(
    "// Generated by scripts/build-wordmark.py; font provenance is in public/brand.\n"
    + "export const lifeAtlasWordmark = " + json.dumps(svg, ensure_ascii=False) + ";\n", encoding="utf-8"
)
shutil.copyfile(SOURCE / "OFL-Alegreya.txt", brand_dir / "OFL-Alegreya.txt")
provenance = {
    "asset": "lifeatlas-wordmark.svg",
    "kind": "outlined typography",
    "family": "Alegreya",
    "copyright": "2011 The Alegreya Project Authors",
    "license": "SIL Open Font License 1.1; see OFL-Alegreya.txt",
    "source": [{"style": style, "url": url, "sha256": hashlib.sha256((SOURCE / filename).read_bytes()).hexdigest()} for style, (filename, url) in FONT_SOURCES.items()],
    "lettering": {"Life": "true italic 550", "Atlas": "roman 500", "alignment": "matched cap heights and shared baseline", "seam_font_units": seam},
    "generator": "scripts/build-wordmark.py",
    "runtime": "inline currentColor SVG; no added font request",
}
(brand_dir / "wordmark-provenance.json").write_text(json.dumps(provenance, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(json.dumps({"viewBox": [width, height], "svg_bytes": len(svg.encode()), "display_height": 156 * height / width}))
